/** Split a quote on `|` — odd segments are the matched span. */
const P = (s: string) => s.split("|").map((text, i) => ({ text, mark: i % 2 === 1 }));

const ev = (
	q: string,
	path: string,
	url: string,
	when: string,
	kind: string,
	conf: number,
): Evidence => ({
	parts: P(q),
	path,
	url,
	when,
	kind,
	conf,
});

const run = (
	when: string,
	dur: string,
	fetched: string,
	cands: string,
	errors: string,
	result: string,
): Run => ({
	when,
	dur,
	fetched,
	cands,
	errors,
	result,
});

